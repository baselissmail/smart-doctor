#!/usr/bin/env node
// Embed the UI fonts as base64 so standalone binaries can serve them without
// node_modules. Output is git-ignored and only needed for binary builds.
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const files = {
  'sans.woff2': '@fontsource-variable/atkinson-hyperlegible-next/files/atkinson-hyperlegible-next-latin-wght-normal.woff2',
  'mono.woff2': '@fontsource-variable/atkinson-hyperlegible-mono/files/atkinson-hyperlegible-mono-latin-wght-normal.woff2',
};
const out = {};
for (const [k, p] of Object.entries(files)) out[k] = (await readFile(require.resolve(p))).toString('base64');
await writeFile(
  new URL('../src/ui/fonts.generated.js', import.meta.url),
  `// Generated by scripts/build-assets.mjs — do not edit.\nexport const FONTS = ${JSON.stringify(out)};\n`,
);
console.log('Wrote src/ui/fonts.generated.js');
